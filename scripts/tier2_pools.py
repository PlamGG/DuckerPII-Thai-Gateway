TRACKING_CARRIERS = ["TH", "KEX", "FLASH", "JNT", "SPX", "EMS", "ED"]

def gen_tracking_number() -> str:
    """Generates realistic e-commerce parcel tracking numbers (10-14 chars)."""
    carrier = random.choice(TRACKING_CARRIERS)
    digits = "".join(str(random.randint(0, 9)) for _ in range(random.choice([10, 11, 12])))
    suffix = random.choice(["TH", "A", "B", ""])
    return f"{carrier}{digits}{suffix}"

def gen_order_id() -> str:
    """Generates order/invoice references (non-PII)."""
    digits = random.randint(10000000, 9999999999)
    prefix = random.choice(["#ORD-", "INV-", "ODR-", "#", "REF:"])
    return f"{prefix}{digits}"

def gen_barcode_or_sku() -> str:
    """Generates product barcodes (EAN-13) and inventory SKU numbers."""
    if random.random() < 0.60:
        return f"885{random.randint(1000000000, 9999999999)}"
    return f"SKU-{random.randint(100000, 999999)}"

def gen_price_tag() -> str:
    """Generates price amounts without comma formatting."""
    amt = random.choice([150, 390, 500, 1200, 2500, 5000, 12000, 25000, 48000])
    unit = random.choice([" บาท", " บ.", ".-", ""])
    return f"{amt}{unit}"

